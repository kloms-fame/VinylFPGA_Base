#!/usr/bin/env python3
"""Generate a fixed Chinese subtitle overlay for the VinylFPGA Base project.

The FPGA receives packed 4-bit glyph IDs.  This tool converts the source text
to unique glyph IDs, rasterizes each glyph into a 16x16 bitmap, and emits both
raw artifacts and a synthesizable Verilog overlay module.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


DEFAULT_TEXT = "你好，欢迎进入选歌环节"
DEFAULT_FONT = r"C:\Windows\Fonts\NotoSansSC-VF.ttf"
DEFAULT_FALLBACK_FONT = r"C:\Windows\Fonts\simhei.ttf"

# Extra glyphs added to the pool on top of printable ASCII.  The pool is what
# the serial terminal may type: anything outside the pool renders as "?".
DEFAULT_EXTRA_CHARS = "，。！？、：；“”‘’（）《》"
# Glyph 0 is a printable replacement so unknown code points stay visible.
REPLACEMENT_CHARACTER = "?"


def parse_args() -> argparse.Namespace:
    repo = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument("--text", default=DEFAULT_TEXT)
    parser.add_argument("--font", default=DEFAULT_FONT)
    parser.add_argument("--glyph-size", type=int, default=16)
    parser.add_argument("--baseline-y", type=int, default=14)
    parser.add_argument("--threshold", type=int, default=96)
    parser.add_argument("--output-dir", default=str(repo / "tools" / "generated"))
    parser.add_argument(
        "--verilog",
        default=str(repo / "src" / "display" / "vinyl_cn_subtitle_overlay.v"),
    )
    return parser.parse_args()


def load_font(font_path: str, fallback_path: str, size: int) -> ImageFont.FreeTypeFont:
    requested = Path(font_path)
    fallback = Path(fallback_path)
    if requested.is_file():
        try:
            return ImageFont.truetype(str(requested), size=size)
        except OSError:
            pass
    if not fallback.is_file():
        raise FileNotFoundError(
            f"Neither font exists: {requested} or {fallback}"
        )
    return ImageFont.truetype(str(fallback), size=size)


def rasterize_glyph(
    character: str,
    font: ImageFont.FreeTypeFont,
    glyph_size: int,
    baseline_y: int,
    threshold: int,
) -> list[int]:
    image = Image.new("L", (glyph_size, glyph_size), 0)
    draw = ImageDraw.Draw(image)

    advance = draw.textlength(character, font=font)
    x = (glyph_size - advance) / 2.0
    baseline = float(baseline_y)

    bbox = draw.textbbox((x, baseline), character, font=font, anchor="ls")
    if bbox[0] < 0:
        x -= bbox[0]
    if bbox[2] > glyph_size:
        x -= bbox[2] - glyph_size
    if bbox[1] < 0:
        baseline -= bbox[1]
    if bbox[3] > glyph_size:
        baseline -= bbox[3] - glyph_size

    draw.text((x, baseline), character, font=font, anchor="ls", fill=255)

    rows: list[int] = []
    for y in range(glyph_size):
        word = 0
        for x_pixel in range(glyph_size):
            if image.getpixel((x_pixel, y)) >= threshold:
                word |= 1 << (glyph_size - 1 - x_pixel)
        rows.append(word)
    return rows


def make_preview(glyphs: list[str], bitmaps: list[list[int]], scale: int = 8) -> Image.Image:
    cell = 16
    gap = 2
    label_h = 10
    width = len(glyphs) * (cell + gap) + gap
    height = cell + label_h + gap * 2
    image = Image.new("RGB", (width * scale, height * scale), (30, 30, 30))
    draw = ImageDraw.Draw(image)
    small_font = ImageFont.load_default()

    for index, (character, rows) in enumerate(zip(glyphs, bitmaps)):
        origin_x = (gap + index * (cell + gap)) * scale
        origin_y = gap * scale
        for y, row_bits in enumerate(rows):
            for x in range(cell):
                on = bool(row_bits & (1 << (cell - 1 - x)))
                color = (255, 255, 255) if on else (0, 0, 0)
                draw.rectangle(
                    [
                        origin_x + x * scale,
                        origin_y + y * scale,
                        origin_x + (x + 1) * scale - 1,
                        origin_y + (y + 1) * scale - 1,
                    ],
                    fill=color,
                )
        draw.text(
            (origin_x, (gap + cell + 1) * scale),
            f"{index:02d}:{character}",
            fill=(255, 220, 120),
            font=small_font,
        )
    return image


def write_generated_verilog(
    path: Path,
    text: str,
    glyphs: list[str],
    text_ids: list[int],
    bitmaps: list[list[int]],
) -> None:
    lines: list[str] = []
    lines.append("`timescale 1ns/1ps")
    lines.append("")
    lines.append("// Generated by tools/generate_cn_subtitle.py. Do not edit by hand.")
    lines.append(f"// Text: {text}")
    lines.append("module vinyl_cn_subtitle_overlay #(")
    lines.append("    parameter integer H_ACTIVE = 640,")
    lines.append("    parameter integer V_ACTIVE = 480,")
    lines.append("    parameter integer CELL_W = 18,")
    lines.append("    parameter integer CELL_H = 18,")
    lines.append("    parameter integer SUBTITLE_Y = V_ACTIVE - 30")
    lines.append(") (")
    lines.append("    input  wire        clk,")
    lines.append("    input  wire        rst_n,")
    lines.append("    input  wire        vsync,")
    lines.append("    input  wire        de,")
    lines.append("    input  wire [9:0]  pixel_x,")
    lines.append("    input  wire [23:0] rgb_in,")
    lines.append("    output wire [23:0] rgb_out,")
    lines.append("    output wire        active")
    lines.append(");")
    lines.append(f"    localparam integer TEXT_LENGTH = {len(text_ids)};")
    lines.append("    localparam integer TEXT_WIDTH = TEXT_LENGTH * CELL_W;")
    lines.append("    localparam integer SUBTITLE_X = (H_ACTIVE - TEXT_WIDTH) / 2;")
    lines.append("")
    lines.append("    reg [11:0] line_y;")
    lines.append("    reg        de_q;")
    lines.append("    reg        vs_q;")
    lines.append("")
    lines.append("    always @(posedge clk or negedge rst_n) begin")
    lines.append("        if (!rst_n) begin")
    lines.append("            line_y <= 12'd0;")
    lines.append("            de_q   <= 1'b0;")
    lines.append("            vs_q   <= 1'b1;")
    lines.append("        end else begin")
    lines.append("            de_q <= de;")
    lines.append("            vs_q <= vsync;")
    lines.append("            if (!vsync)")
    lines.append("                line_y <= 12'd0;")
    lines.append("            else if (de_q && !de)")
    lines.append("                line_y <= line_y + 1'b1;")
    lines.append("        end")
    lines.append("    end")
    lines.append("")
    lines.append("    function [3:0] text_glyph_id;")
    lines.append("        input integer index;")
    lines.append("        begin")
    lines.append("            case (index)")
    for index, glyph_id in enumerate(text_ids):
        lines.append(f"                {index}: text_glyph_id = 4'd{glyph_id};")
    lines.append("                default: text_glyph_id = 4'd0;")
    lines.append("            endcase")
    lines.append("        end")
    lines.append("    endfunction")
    lines.append("")
    lines.append("    function [15:0] glyph_row;")
    lines.append("        input [3:0] glyph_id;")
    lines.append("        input [3:0] row;")
    lines.append("        reg [15:0] row_bits;")
    lines.append("        begin")
    lines.append("            row_bits = 16'h0000;")
    lines.append("            case (glyph_id)")
    for glyph_id, rows in enumerate(bitmaps):
        lines.append(f"                4'd{glyph_id}: begin")
        lines.append("                    case (row)")
        for row_index, row_bits in enumerate(rows):
            lines.append(
                f"                        4'd{row_index}: row_bits = 16'h{row_bits:04X};"
            )
        lines.append("                        default: row_bits = 16'h0000;")
        lines.append("                    endcase")
        lines.append("                end")
    lines.append("                default: row_bits = 16'h0000;")
    lines.append("            endcase")
    lines.append("            glyph_row = row_bits;")
    lines.append("        end")
    lines.append("    endfunction")
    lines.append("")
    lines.append("    integer char_index;")
    lines.append("    integer dx;")
    lines.append("    integer glyph_col;")
    lines.append("    reg [15:0] selected_row;")
    lines.append("    reg        band_pixel;")
    lines.append("    reg        text_pixel;")
    lines.append("")
    lines.append("    always @* begin")
    lines.append("        char_index  = 0;")
    lines.append("        dx          = 0;")
    lines.append("        glyph_col   = 0;")
    lines.append("        selected_row = 16'h0000;")
    lines.append("        band_pixel  = 1'b0;")
    lines.append("        text_pixel  = 1'b0;")
    lines.append("")
    lines.append("        if (de &&")
    lines.append("            pixel_x >= SUBTITLE_X &&")
    lines.append("            pixel_x < SUBTITLE_X + TEXT_WIDTH &&")
    lines.append("            line_y >= SUBTITLE_Y &&")
    lines.append("            line_y < SUBTITLE_Y + CELL_H) begin")
    lines.append("            band_pixel = 1'b1;")
    lines.append("            dx = pixel_x - SUBTITLE_X;")
    lines.append("            char_index = dx / CELL_W;")
    lines.append("            glyph_col = dx - char_index * CELL_W;")
    lines.append("")
    lines.append("            if (glyph_col >= 1 && glyph_col <= 16 &&")
    lines.append("                line_y >= SUBTITLE_Y + 1 &&")
    lines.append("                line_y < SUBTITLE_Y + 17) begin")
    lines.append("                selected_row = glyph_row(")
    lines.append("                    text_glyph_id(char_index),")
    lines.append("                    line_y - SUBTITLE_Y - 1);")
    lines.append("                text_pixel = selected_row[15 - (glyph_col - 1)];")
    lines.append("            end")
    lines.append("        end")
    lines.append("    end")
    lines.append("")
    lines.append("    assign active = band_pixel;")
    lines.append("    assign rgb_out = band_pixel ?")
    lines.append("                     (text_pixel ? 24'hFFFFFF : 24'h101010) : rgb_in;")
    lines.append("endmodule")
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    args = parse_args()
    characters = list(args.text)
    unique_glyphs: list[str] = []
    glyph_ids: dict[str, int] = {}
    text_ids: list[int] = []

    for character in characters:
        if character not in glyph_ids:
            glyph_ids[character] = len(unique_glyphs)
            unique_glyphs.append(character)
        text_ids.append(glyph_ids[character])

    if len(unique_glyphs) > 16:
        raise ValueError("This generated format supports at most 16 unique glyphs.")

    font = load_font(args.font, DEFAULT_FALLBACK_FONT, args.glyph_size)
    bitmaps = [
        rasterize_glyph(
            character,
            font,
            args.glyph_size,
            args.baseline_y,
            args.threshold,
        )
        for character in unique_glyphs
    ]

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    with (output_dir / "glyph_index.csv").open("w", newline="", encoding="utf-8") as csv_file:
        writer = csv.writer(csv_file)
        writer.writerow(["glyph_id", "character", "unicode"])
        for glyph_id, character in enumerate(unique_glyphs):
            writer.writerow([glyph_id, character, f"U+{ord(character):04X}"])

    with (output_dir / "text_ids.bin").open("wb") as binary_file:
        for glyph_id in text_ids:
            binary_file.write(glyph_id.to_bytes(2, "little"))

    with (output_dir / "font_bitmap.bin").open("wb") as binary_file:
        for rows in bitmaps:
            for row_bits in rows:
                binary_file.write(row_bits.to_bytes(2, "big"))

    preview = make_preview(unique_glyphs, bitmaps)
    preview.save(output_dir / "font_preview.png")

    (output_dir / "subtitle.txt").write_text(args.text + "\n", encoding="utf-8")

    write_generated_verilog(
        Path(args.verilog),
        args.text,
        unique_glyphs,
        text_ids,
        bitmaps,
    )

    print(f"TEXT={args.text}")
    print(f"GLYPHS={len(unique_glyphs)}")
    print(f"TEXT_LENGTH={len(text_ids)}")
    print(f"GLYPH_IDS={','.join(str(value) for value in text_ids)}")
    print(f"OUTPUT_DIR={output_dir}")
    print(f"VERILOG={Path(args.verilog)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
