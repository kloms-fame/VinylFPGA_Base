// ==========================================================================
// 麦克风数字增益跟随用户音量（VOL）
//   VOL 由参数 CSR 提供，范围 0..200（200 = 满音量）。固定 5.0x 在低音量时
//   会把底噪放大得比音乐还响，因此让麦克风增益随 VOL 线性变化：
//     VOL = 200 -> 5.0x，VOL = 100 -> 2.5x，VOL = 0 -> 0（自然静音）。
//   增益单位 1/32：gain_q5 = round(VOL * 4 / 5) = VOL - round(VOL / 5)。
//   实现只用移位加/减法（51/256 逼近 1/5），不占乘法器、不引入除法器。
//   下游 mic_pcm_mixer 的 8/64 帧增益斜坡会平滑每次 VOL 变化，不产生咔哒声。
// ==========================================================================
`timescale 1ns / 1ps
module mic_gain_follow (
    input  wire [7:0] volume,   // play_volume_video, 0..200
    output wire [7:0] gain_q5   // 0..160, 1/32 单位，160 = 5.0x
);
    // VOL 超过 200 时按 200 封顶，防止参数区异常值把麦克风过驱。
    wire [7:0]  vol_eff = (volume > 8'd200) ? 8'd200 : volume;
    wire [15:0] v       = {8'd0, vol_eff};
    // round(v * 51 / 256) 近似 v/5，误差 <= 1/256 个 v。
    wire [15:0] v_x51   = (v << 5) + (v << 4) + (v << 1) + v;
    wire [15:0] v_div5  = (v_x51 + 16'd128) >> 8;
    assign gain_q5 = (v >= v_div5) ? (vol_eff - v_div5[7:0]) : 8'd0;
endmodule
